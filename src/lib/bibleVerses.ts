/**
 * Seleciona o versículo ideal para meditação baseado no desabafo e estado emocional,
 * priorizando passagens de combate à ansiedade da Bíblia Online quando ansiedade for detectada.
 */
export function getBibleVerseForMentalDump(
  text: string,
  sentiment?: string,
  keywords: string[] = []
): BiblicalVerseForMeditation {
  const lower = (text || '').toLowerCase();
  const kwJoin = keywords.join(' ').toLowerCase();

  const isAnxious = 
    sentiment === 'ansioso' ||
    lower.includes('ansios') ||
    lower.includes('angústia') ||
    lower.includes('pânico') ||
    lower.includes('medo') ||
    lower.includes('preocupad') ||
    lower.includes('inquieta') ||
    lower.includes('coração acelerado') ||
    kwJoin.includes('ansiedade') ||
    kwJoin.includes('preocupação');

  const isExhausted =
    sentiment === 'exausto' ||
    lower.includes('exaust') ||
    lower.includes('cansad') ||
    lower.includes('sem energia') ||
    lower.includes('dormir') ||
    lower.includes('insônia') ||
    kwJoin.includes('exaustão') ||
    kwJoin.includes('sono');

  const isOverwhelmed =
    sentiment === 'sobrecarregado' ||
    lower.includes('sobrecarreg') ||
    lower.includes('caos') ||
    lower.includes('não aguento') ||
    lower.includes('socorro') ||
    lower.includes('muita coisa') ||
    kwJoin.includes('sobrecarga') ||
    kwJoin.includes('caos mental');

  if (isAnxious) {
    // Escolhe entre os versículos específicos de combate à ansiedade da bibliaonline
    const anxietyVerses = ANXIETY_MEDITATION_VERSES.filter(v => v.isAnxietyVerse);
    // Hash determinístico baseado no texto para consistência ou rotação
    const hash = Math.abs(lower.split('').reduce((acc, char) => acc + char.charCodeAt(0), 0));
    return anxietyVerses[hash % anxietyVerses.length];
  }

  if (isExhausted) {
    // Mateus 11:28-29 (Descanso para a alma) ou Salmos 23
    return ANXIETY_MEDITATION_VERSES.find(v => v.reference.includes('Mateus 11')) || ANXIETY_MEDITATION_VERSES[10];
  }

  if (isOverwhelmed) {
    // Salmos 46:1,10 ou Salmos 55:22 ou 1 Pedro 5:7
    return ANXIETY_MEDITATION_VERSES.find(v => v.reference.includes('Salmos 55')) || ANXIETY_MEDITATION_VERSES[1];
  }

  // Positivo / Neutro / Foco
  const hash = Math.abs(lower.split('').reduce((acc, char) => acc + char.charCodeAt(0), 0));
  return ANXIETY_MEDITATION_VERSES[hash % ANXIETY_MEDITATION_VERSES.length];
}
